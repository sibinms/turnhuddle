const { receiveMessage, receiveProgress, finishConversation, resumeConversation, initialState } = require('../dist/conversationView');
const t0 = new Date('2026-11-25T10:00:00.000Z');
const at = seconds => new Date(t0.getTime() + seconds * 1000);
