const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const runRound = (manager, id, start = 0) => {
  manager.update(id, s => receiveMessage(s, id, { role: 'user', content: s.task }, at(start)), at(start));
  for (const [role, offset] of [['claude', 10], ['codex', 30], ['claude', 50]]) manager.update(id, s => receiveMessage(s, id, { role, content: `${role} says` }, at(start + offset)), at(start + offset));
  manager.update(id, s => finishConversation(s, 'completed', at(start + 51)), at(start + 51));
};
test('create, update and select drive the panel state and the list', () => {
  const manager = new SessionManager();
  const states = []; const lists = [];
  manager.subscribe(s => states.push(s.status)); manager.onDidChangeList(() => lists.push(manager.list().map(c => c.id)));
  assert.deepEqual(manager.get(), initialState()); assert.equal(manager.selectedId(), undefined);
  const a = manager.create('a', 'Task A', '/work/a', at(0));
  assert.equal(a.status, 'running'); assert.equal(a.cwd, '/work/a'); assert.equal(a.archived, false);
  assert.equal(manager.selectedId(), 'a'); assert.equal(manager.get().task, 'Task A');
  runRound(manager, 'a');
  assert.equal(manager.get().status, 'completed'); assert.equal(manager.get().messages.length, 4);
  const b = manager.create('b', 'Task B', '/work/b', at(100));
  assert.equal(manager.selectedId(), 'b'); assert.deepEqual(manager.list().map(c => c.id), ['b', 'a'], 'newest activity first');
  assert.ok(manager.select('a')); assert.equal(manager.get().task, 'Task A');
  assert.equal(manager.select('missing'), false); assert.equal(manager.selectedId(), 'a');
  assert.ok(manager.select(undefined)); assert.deepEqual(manager.get(), initialState(), 'nothing selected shows the welcome state');
  assert.equal(manager.list().length, 2, 'deselecting keeps both conversations');
  manager.update('b', s => receiveMessage(s, 'b', { role: 'user', content: 'Task B' }, at(101)), at(101));
  assert.equal(manager.get().status, 'idle', 'updating an unselected conversation leaves the panel alone');
  assert.equal(manager.getConversation('b').messages.length, 1);
  assert.ok(states.includes('running') && states.includes('completed')); assert.ok(lists.length >= 3);
  assert.equal(b.id, 'b');
});
test('summaries, archive and restore', () => {
  const manager = new SessionManager();
  manager.create('a', '  A long   task \n description ' + 'x'.repeat(100), '/w', at(0)); runRound(manager, 'a');
  manager.create('b', 'Task B', '/w', at(100));
  const other = new SessionManager(); other.create('c', 'x'.repeat(200), '/w', at(50));
  assert.ok(other.summaries()[0].title.length <= 60 && other.summaries()[0].title.endsWith('…'));
  const [first, second] = manager.summaries();
  assert.equal(first.id, 'b'); assert.equal(first.status, 'running'); assert.equal(first.rounds, 0);
  assert.equal(second.id, 'a'); assert.equal(second.status, 'completed'); assert.equal(second.rounds, 1); assert.equal(second.messages, 4);
  assert.equal(second.title, 'A long task', 'named after the first line');
  assert.ok(manager.setArchived('b', true));
  assert.equal(manager.selectedId(), undefined, 'archiving the selected conversation deselects it');
  assert.deepEqual(manager.list().map(c => c.id), ['a']); assert.deepEqual(manager.archived().map(c => c.id), ['b']);
  assert.deepEqual(manager.summaries().map(s => [s.id, s.archived]), [['a', false], ['b', true]]);
  assert.ok(manager.setArchived('b', false)); assert.equal(manager.archived().length, 0);
  assert.equal(manager.setArchived('zzz', true), false);
});
test('conversations persist to one JSON file each and load back without partial text', async () => {
  const dir = tmp();
  const manager = new SessionManager(new HistoryStore(dir), 10);
  manager.create('a', 'Task A', '/work/a', at(0));
  runRound(manager, 'a');
  manager.create('b', 'Task B', '/work/b', at(100));
  manager.update('b', s => receiveMessage(s, 'b', { role: 'user', content: 'Task B' }, at(101)), at(101));
  manager.update('b', s => receiveProgress(s, 'claude', { type: 'delta', text: 'streamed' }));
  await manager.flush(); await sleep(50);
  const files = fs.readdirSync(dir).sort();
  assert.deepEqual(files, ['a.json', 'b.json']);
  const a = JSON.parse(fs.readFileSync(path.join(dir, 'a.json'), 'utf8'));
  assert.equal(a.id, 'a'); assert.equal(a.status, 'completed'); assert.equal(a.messages.length, 4); assert.equal(a.cwd, '/work/a'); assert.equal(a.archived, false);
  const b = JSON.parse(fs.readFileSync(path.join(dir, 'b.json'), 'utf8'));
  assert.equal(b.partial, undefined, 'streamed text is not written');
  const reloaded = new SessionManager(new HistoryStore(dir));
  assert.equal(await reloaded.load(), 2);
  assert.equal(reloaded.selectedId(), undefined);
  assert.deepEqual(reloaded.list().map(c => c.id), ['b', 'a']);
  assert.equal(reloaded.getConversation('a').messages[3].content, 'claude says');
  const interrupted = reloaded.getConversation('b');
  assert.equal(interrupted.status, 'failed', 'a conversation that was running when the window closed is marked failed');
  assert.match(interrupted.error, /window closed/);
  assert.equal(interrupted.messages.length, 1);
  assert.equal(manager.lastError, undefined);
});
test('archiving writes immediately and reload keeps the flag; a resumed round saves again', async () => {
  const dir = tmp();
  const manager = new SessionManager(new HistoryStore(dir), 10);
  manager.create('a', 'Task A', '/w', at(0)); runRound(manager, 'a');
  manager.setArchived('a', true);
  await sleep(40);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'a.json'), 'utf8')).archived, true);
  const reloaded = new SessionManager(new HistoryStore(dir), 10);
  await reloaded.load();
  assert.deepEqual(reloaded.archived().map(c => c.id), ['a']);
  reloaded.setArchived('a', false); reloaded.select('a');
  reloaded.update('a', s => resumeConversation(s, at(200)), at(200));
  runRound(reloaded, 'a', 201);
  await reloaded.flush(); await sleep(30);
  const saved = JSON.parse(fs.readFileSync(path.join(dir, 'a.json'), 'utf8'));
  assert.equal(saved.messages.length, 8); assert.equal(saved.archived, false); assert.equal(saved.status, 'completed');
});
